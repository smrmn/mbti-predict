def calculate_mbti(answers: list[str]) -> str:
    """
    answers — список из 16 элементов, каждый 'a' или 'b'.
    Возвращает строку типа 'INFP'.
    """
    scores = {"EI": 0, "SN": 0, "TF": 0, "JP": 0}

    for answer, question in zip(answers, QUESTIONS):
        if answer == "a":
            scores[question["scale"]] += 1  # +1 к первому полюсу

    mbti = ""
    mbti += "E" if scores["EI"] >= 2 else "I"
    mbti += "S" if scores["SN"] >= 2 else "N"
    mbti += "T" if scores["TF"] >= 2 else "F"
    mbti += "J" if scores["JP"] >= 2 else "P"
    return mbti


def get_description(mbti: str) -> str:
    return MBTI_DESCRIPTIONS.get(mbti, "Уникальный тип 🌀")
